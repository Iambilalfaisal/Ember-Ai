"""Regenerate the contracts between the backend and its clients (``contracts/``).

Run with ``uv run poe openapi`` from ``backend/``. It writes, deterministically:

``contracts/openapi.json``
    The HTTP API's OpenAPI document, built from the app itself (AGENTS.md section 5).
``contracts/ts/api/``
    A typed TypeScript client for it: ``schema.d.ts`` (every path, body and response, from
    ``openapi-typescript``) and ``client.ts`` (``createApiClient``, a thin ``openapi-fetch``
    wrapper).
``contracts/realtime/``
    JSON Schema of the live-call WebSocket protocol, one file per direction (AGENTS.md section 6).
``contracts/ts/realtime/``
    TypeScript types generated from those schemas, plus the protocol constants (version, id
    pattern, close codes).

Nothing in those places is edited by hand. CI regenerates them and fails on any difference
(``scripts/check_openapi_drift.py``), so a backend change that alters a contract cannot merge
until the regenerated files are committed with it.

The TypeScript is generated by ``openapi-typescript`` and ``json-schema-to-typescript``. Their
versions are pinned in ``contracts/package.json`` and ``package-lock.json`` (and installed on
first use with ``npm ci``), so the output only changes when the backend or a pin changes. This
needs Node.js 20 or newer.
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Final

from pydantic import SecretStr

from ember.core.config import AiSettings, DbSettings, RedisSettings, Settings
from ember.entrypoints.api import create_app
from ember.modules.calls.public import live_protocol_constants, live_protocol_schemas

BACKEND: Final = Path(__file__).resolve().parent.parent
REPO: Final = BACKEND.parent
CONTRACTS: Final = REPO / "contracts"

# What this script owns inside contracts/. The drift check compares exactly these paths; the
# rest of contracts/ (package.json, lock file, tsconfig.json, README.md) is written by hand.
GENERATED_FILES: Final = ("openapi.json",)
GENERATED_DIRECTORIES: Final = ("realtime", "ts")

_GENERATED_NOTE: Final = (
    "// Generated by backend/scripts/export_openapi.py. Do not edit; run `uv run poe openapi`."
)

_CLIENT_TS: Final = """\
// Generated by backend/scripts/export_openapi.py. Do not edit; run `uv run poe openapi`.
import createClient, { type ClientOptions } from "openapi-fetch";

import type { paths } from "./schema";

/**
 * A typed fetch client for the Ember API: every path, method, request body and response
 * is checked against the backend's OpenAPI document.
 *
 * Pass `baseUrl` and, for signed-in calls, an `Authorization: Bearer <token>` header.
 */
export function createApiClient(options: ClientOptions) {
  return createClient<paths>(options);
}
"""

_API_INDEX_TS: Final = """\
// Generated by backend/scripts/export_openapi.py. Do not edit; run `uv run poe openapi`.
export { createApiClient } from "./client";
export type { components, paths } from "./schema";
"""

_REALTIME_INDEX_TS: Final = """\
// Generated by backend/scripts/export_openapi.py. Do not edit; run `uv run poe openapi`.
export * from "./client";
export * from "./constants";
export * from "./server";
"""

_ROOT_INDEX_TS: Final = """\
// Generated by backend/scripts/export_openapi.py. Do not edit; run `uv run poe openapi`.
export * from "./api";
export * as realtime from "./realtime";
"""


def contracts_settings() -> Settings:
    """Settings for building the app just to read its routes.

    Fixed values and no ``.env``, so the output never depends on the developer's machine. The
    database and Redis are never contacted: building the app does no I/O.
    """
    return Settings(
        _env_file=None,  # type: ignore[call-arg]
        env="test",
        db=DbSettings(
            url=SecretStr("postgresql+asyncpg://contracts:contracts@127.0.0.1:1/contracts")
        ),
        redis=RedisSettings(url=SecretStr("redis://127.0.0.1:1/0")),
        ai=AiSettings(tasks_config_path=BACKEND / "config" / "ai_tasks.yaml"),
    )


def openapi_document() -> dict[str, Any]:
    """The HTTP API's OpenAPI document."""
    return create_app(contracts_settings()).openapi()


def render_json(document: object) -> str:
    """JSON with a fixed layout (sorted keys, two-space indent, trailing newline)."""
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_constants_ts(constants: dict[str, Any]) -> str:
    """The protocol constants as a TypeScript module."""
    close_codes = "".join(f"  {name}: {code},\n" for name, code in constants["CLOSE_CODES"].items())
    return (
        f"{_GENERATED_NOTE}\n"
        f"export const PROTOCOL_VERSION = {constants['PROTOCOL_VERSION']} as const;\n"
        "\n"
        "/** Ids the desktop chooses (an utterance, a card) must match this pattern. */\n"
        f"export const ID_PATTERN = {json.dumps(constants['ID_PATTERN'])};\n"
        "\n"
        "/** WebSocket close codes: why the server closed the connection. */\n"
        f"export const CloseCode = {{\n{close_codes}}} as const;\n"
        "\n"
        "export type CloseCode = (typeof CloseCode)[keyof typeof CloseCode];\n"
    )


class ToolError(RuntimeError):
    """A Node tool is missing or failed."""


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")  # LF everywhere, also on Windows


def _node_tool(name: str) -> str:
    """Path of a generator in ``contracts/node_modules`` (runs ``npm ci`` first if needed)."""
    bin_directory = CONTRACTS / "node_modules" / ".bin"
    found = shutil.which(name, path=str(bin_directory))
    if found is not None:
        return found
    npm = shutil.which("npm")
    if npm is None:
        raise ToolError("Node.js 20 or newer (with npm) is needed to generate the TypeScript.")
    sys.stdout.write("export_openapi: installing the TypeScript generators (npm ci)\n")
    subprocess.run([npm, "ci", "--no-audit", "--no-fund"], cwd=CONTRACTS, check=True)
    found = shutil.which(name, path=str(bin_directory))
    if found is None:
        raise ToolError(f"{name} is not installed; check contracts/package.json.")
    return found


def _run_tool(name: str, *arguments: str) -> None:
    subprocess.run([_node_tool(name), *arguments], cwd=CONTRACTS, check=True)


def generate(out: Path) -> None:
    """Write every generated file under ``out`` (replacing what was generated there before)."""
    for directory in GENERATED_DIRECTORIES:
        shutil.rmtree(out / directory, ignore_errors=True)

    openapi_path = out / "openapi.json"
    _write(openapi_path, render_json(openapi_document()))

    api = out / "ts" / "api"
    api.mkdir(parents=True, exist_ok=True)
    _run_tool("openapi-typescript", str(openapi_path), "--output", str(api / "schema.d.ts"))
    _write(api / "client.ts", _CLIENT_TS)
    _write(api / "index.ts", _API_INDEX_TS)

    realtime_schemas = out / "realtime"
    realtime_types = out / "ts" / "realtime"
    for direction, schema in live_protocol_schemas().items():
        schema_path = realtime_schemas / f"{direction}.schema.json"
        _write(schema_path, render_json(schema))
        _run_tool(
            "json2ts",
            "--input",
            str(schema_path),
            "--output",
            str(realtime_types / f"{direction}.ts"),
            "--no-additionalProperties",
        )
    _write(realtime_types / "constants.ts", render_constants_ts(live_protocol_constants()))
    _write(realtime_types / "index.ts", _REALTIME_INDEX_TS)
    _write(out / "ts" / "index.ts", _ROOT_INDEX_TS)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument(
        "--out",
        type=Path,
        default=CONTRACTS,
        help="write here instead of contracts/ (used by the drift check)",
    )
    arguments = parser.parse_args()
    try:
        generate(arguments.out)
    except ToolError as error:
        sys.stderr.write(f"export_openapi: {error}\n")
        return 1
    sys.stdout.write(f"export_openapi: wrote {arguments.out}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
